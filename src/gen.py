def fmt(x):
    if isinstance(x, float):
        if abs(x - round(x)) < 1e-9:
            return str(int(round(x)))
        return f"{x:.2f}".rstrip('0').rstrip('.').replace('.', ',')
    return str(x)


def pl(n, one, few, many):
    n10, n100 = n % 10, n % 100
    w = one if n10 == 1 and n100 != 11 else few if 2 <= n10 <= 4 and not 12 <= n100 <= 14 else many
    return f"{n} {w}"

def raz(k):
    return f"в {k} раз" + ("а" if k % 10 in (2, 3, 4) and not 12 <= k % 100 <= 14 else "")

def Q(q, correct, wrong, e):
    opts = [correct] + list(wrong)
    assert len(opts) == 4 and len(set(opts)) == 4, (q, opts)
    return {"q": q, "c": correct, "w": list(wrong), "e": e}

def nums(ans, rng, extra=(), unit='', allow_zero=False):
    """Правильный ответ + 3 правдоподобных неверных числа."""
    others = [ans + 1, ans - 1, ans + 2, ans - 2, ans * 2, ans / 2, ans + 10, ans - 10,
              ans + 5, ans - 5, ans * 3, ans * 1.5, ans + 20, ans + 3]
    rng.shuffle(others)
    pool = list(extra) + others
    seen = {fmt(ans)}
    out = []
    for c in pool:
        if c < 0 or (c == 0 and not allow_zero):
            continue
        if isinstance(c, float) and abs(c * 100 - round(c * 100)) > 1e-9:
            continue
        s = fmt(c)
        if s in seen:
            continue
        seen.add(s)
        out.append(s + unit)
        if len(out) == 3:
            break
    return fmt(ans) + unit, out

def NQ(q, ans, rng, e, extra=(), unit='', allow_zero=False):
    c, w = nums(ans, rng, extra, unit, allow_zero)
    return Q(q, c, w, e)

def C(lst):
    return [Q(*t) for t in lst]

