def assemble(concept, pools, n=200, seed=0):
    out = []
    for q in concept:
        if q["q"] not in SEEN:
            SEEN.add(q["q"]); out.append(q)
    pools = [[q for q in p] for p in pools]
    i = 0
    while len(out) < n and any(pools):
        p = pools[i % len(pools)]
        while p:
            q = p.pop(0)
            if q["q"] not in SEEN:
                SEEN.add(q["q"]); out.append(q); break
        i += 1
    assert len(out) >= n, f"only {len(out)}"
    out = out[:n]
    random.Random(seed).shuffle(out)
    return out

